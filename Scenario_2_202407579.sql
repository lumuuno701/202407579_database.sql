CREATE OR REPLACE PROCEDURE sc2_lab.show_low_sessions(p_threshold integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR (p_limit integer) FOR
        SELECT session_name, available_workstations
        FROM sc2_lab.lab_sessions
        WHERE available_workstations <= p_limit
        ORDER BY session_id;
BEGIN
    OPEN c_low(p_threshold);
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;          
        RAISE NOTICE 'Few workstations left: "%" (% remaining)', v_item.session_name, v_item.available_workstations;
    END LOOP;
    CLOSE c_low;
END;
$$;

