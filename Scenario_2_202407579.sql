CREATE OR REPLACE PROCEDURE sc2_lab.cancel_reservation(p_reservation_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_item_id integer;
    v_qty     integer;
BEGIN
    SELECT session_id, workstations
    INTO v_item_id, v_qty
    FROM sc2_lab.reservations
    WHERE reservation_id = p_reservation_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active reservation with ID %', p_reservation_id;
        RETURN;
    END IF;

    UPDATE sc2_lab.reservations
    SET status = 'CANCELLED'
    WHERE reservation_id = p_reservation_id;

    UPDATE sc2_lab.lab_sessions
    SET available_workstations = available_workstations + v_qty
    WHERE session_id = v_item_id;

    RAISE NOTICE 'Reservation % cancelled; % workstations released', p_reservation_id, v_qty;
END;
$$;

