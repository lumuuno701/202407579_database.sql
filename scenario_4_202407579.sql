CREATE OR REPLACE PROCEDURE sc4_clinic.reverse_dispensing(p_record_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_item_id integer;
    v_qty     integer;
BEGIN
    SELECT medicine_id, quantity
    INTO v_item_id, v_qty
    FROM sc4_clinic.dispensing_records
    WHERE record_id = p_record_id AND status = 'DISPENSED'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No dispensed record that can be reversed with ID %', p_record_id;
        RETURN;
    END IF;

    UPDATE sc4_clinic.dispensing_records
    SET status = 'REVERSED'
    WHERE record_id = p_record_id;

    UPDATE sc4_clinic.medicines
    SET stock_quantity = stock_quantity + v_qty
    WHERE medicine_id = v_item_id;

    RAISE NOTICE 'Dispensing record % reversed; % units restored to stock', p_record_id, v_qty;
END;
$$;

