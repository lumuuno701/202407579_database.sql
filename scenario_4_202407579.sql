CREATE OR REPLACE PROCEDURE sc4_clinic.show_low_medicines(p_threshold integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR (p_limit integer) FOR
        SELECT medicine_name, stock_quantity
        FROM sc4_clinic.medicines
        WHERE stock_quantity <= p_limit
        ORDER BY medicine_id;
BEGIN
    OPEN c_low(p_threshold);
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;          
        RAISE NOTICE 'Below threshold: "%" (% in stock)', v_item.medicine_name, v_item.stock_quantity;
    END LOOP;
    CLOSE c_low;
END;
$$;

