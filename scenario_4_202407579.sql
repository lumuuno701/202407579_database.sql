CREATE OR REPLACE PROCEDURE sc4_clinic.dispense_medicine(
    p_medicine_id   integer,
    p_student_number text,
    p_quantity   integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_available integer;
    v_new_id    integer;
BEGIN
  
    IF p_quantity <= 0 THEN
        RAISE EXCEPTION 'Quantity must be positive'
            USING ERRCODE = '22023';          
    END IF;
    IF p_student_number IS NULL OR btrim(p_student_number) = '' THEN
        RAISE EXCEPTION 'Student must not be blank'
            USING ERRCODE = '22023';
    END IF;

   
    SELECT stock_quantity INTO v_available
    FROM sc4_clinic.medicines
    WHERE medicine_id = p_medicine_id
    FOR UPDATE;

    
    IF NOT FOUND THEN
        RAISE NOTICE 'Medicine % does not exist', p_medicine_id;
        RETURN;
    ELSIF v_available < p_quantity THEN
        RAISE NOTICE 'Insufficient stock: only % available', v_available;
        RETURN;
    END IF;

    UPDATE sc4_clinic.medicines
    SET stock_quantity = stock_quantity - p_quantity
    WHERE medicine_id = p_medicine_id;

    INSERT INTO sc4_clinic.dispensing_records (medicine_id, student_number, quantity, status)
    VALUES (p_medicine_id, p_student_number, p_quantity, 'DISPENSED')
    RETURNING record_id INTO v_new_id;

    RAISE NOTICE 'Dispensing record % recorded for student %', v_new_id, p_student_number;
END;
$$;


