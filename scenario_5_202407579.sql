CREATE OR REPLACE PROCEDURE sc5_workshop.return_tool(p_loan_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_item_id integer;
    v_qty     integer;
BEGIN
    SELECT tool_id, quantity
    INTO v_item_id, v_qty
    FROM sc5_workshop.tool_loans
    WHERE loan_id = p_loan_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active tool loan with ID %', p_loan_id;
        RETURN;
    END IF;

    UPDATE sc5_workshop.tool_loans
    SET status = 'RETURNED'
    WHERE loan_id = p_loan_id;

    UPDATE sc5_workshop.tools
    SET available_quantity = available_quantity + v_qty
    WHERE tool_id = v_item_id;

    RAISE NOTICE 'Tool loan % returned; % tools added back to stock', p_loan_id, v_qty;
END;
$$;

