CREATE OR REPLACE PROCEDURE sc5_workshop.show_low_tools(p_threshold integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR (p_limit integer) FOR
        SELECT tool_name, available_quantity
        FROM sc5_workshop.tools
        WHERE available_quantity <= p_limit
        ORDER BY tool_id;
BEGIN
    OPEN c_low(p_threshold);
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;          
        RAISE NOTICE 'Low availability: "%" (% left)', v_item.tool_name, v_item.available_quantity;
    END LOOP;
    CLOSE c_low;
END;
$$;

