DO $$
DECLARE
    r record;
BEGIN
    FOR r IN SELECT event_name, available_seats FROM sc6_events.events ORDER BY event_id LOOP
        IF r.available_seats = 0 THEN
            RAISE NOTICE 'Event "%" is full', r.event_name;
        ELSIF r.available_seats <= 10 THEN
            RAISE NOTICE 'Event "%" is nearly full: % seats left', r.event_name, r.available_seats;
        ELSE
            RAISE NOTICE 'Event "%" has plenty of seats: %', r.event_name, r.available_seats;
        END IF;
    END LOOP;
END;
$$ LANGUAGE plpgsql;


