CREATE OR REPLACE PROCEDURE sc6_events.book_seats(
    p_event_id   integer,
    p_student_number text,
    p_seats   integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_available integer;
    v_new_id    integer;
BEGIN
    
    IF p_seats <= 0 THEN
        RAISE EXCEPTION 'Number of seats must be positive'
            USING ERRCODE = '22023';          
    END IF;
    IF p_student_number IS NULL OR btrim(p_student_number) = '' THEN
        RAISE EXCEPTION 'Student must not be blank'
            USING ERRCODE = '22023';
    END IF;

    
    SELECT available_seats INTO v_available
    FROM sc6_events.events
    WHERE event_id = p_event_id
    FOR UPDATE;

   
    IF NOT FOUND THEN
        RAISE NOTICE 'Event % does not exist', p_event_id;
        RETURN;
    ELSIF v_available < p_seats THEN
        RAISE NOTICE 'Insufficient seats: only % available', v_available;
        RETURN;
    END IF;

    UPDATE sc6_events.events
    SET available_seats = available_seats - p_seats
    WHERE event_id = p_event_id;

    INSERT INTO sc6_events.bookings (event_id, student_number, seats, status)
    VALUES (p_event_id, p_student_number, p_seats, 'CONFIRMED')
    RETURNING booking_id INTO v_new_id;

    RAISE NOTICE 'Booking % recorded for student %', v_new_id, p_student_number;
END;
$$;
